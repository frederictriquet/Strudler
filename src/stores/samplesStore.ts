// [SPEC-12.1/12.2, SPEC-14.4] Base sound bank. Served from a local, user-owned
// folder (~/Music/Sounds) by the dev/preview server (see vite-plugins/
// soundsServer.ts), scanned on each load. Fully offline; drop in dirt-samples
// (npm run samples:fetch) and any personal sounds — they are picked up
// automatically.

import { writable } from 'svelte/store';
import { engine } from '@core/engine/StrudelEngine';
import { loadAllBanks, LOCAL_BANK_URL, soundfontNotice } from '@core/engine/sampleBanks';
import { notify } from '@stores/logStore';

export type SamplesStatus = 'idle' | 'loading' | 'ready' | 'error';

/** Local sample-library map generated by the sounds server (same-origin). */
export const DEFAULT_SAMPLE_BANK = LOCAL_BANK_URL;

export const samplesStatus = writable<SamplesStatus>('idle');
export const samplesError = writable<string | null>(null);

// Shared in-flight promise: many callers can await the same single load, and a
// failed load can be retried (promise cleared on error).
let loadPromise: Promise<void> | null = null;

/** Load the default bank (once). Await it before playing sample-based tracks so
 *  the sound names are registered (avoids "sound X not found"). [SPEC-12.1] */
export function loadDefaultSamples(): Promise<void> {
  if (loadPromise) return loadPromise;
  samplesStatus.set('loading');
  samplesError.set(null);
  // Local bank first, then the very banks the REPL preloads, so a pattern sounds
  // the same in both [SPEC-17.54]. A partial load is the normal degraded mode.
  loadPromise = loadAllBanks(engine)
    .then((result) => {
      if (result.loaded.length === 0) {
        const message = `Aucune banque de sons chargée : ${result.failed.map((f) => f.label).join(', ')}`;
        samplesStatus.set('error');
        samplesError.set(message);
        notify('error', message);
        loadPromise = null; // allow a retry
        return;
      }
      samplesStatus.set('ready');
      samplesError.set(null);
      notify('success', `Banques de sons chargées (${result.loaded.length})`);
      // Named, never silent: a missing bank means missing sounds later. [SPEC-14.3]
      for (const f of result.failed) {
        notify('warn', `Banque « ${f.label} » indisponible : ${f.message}`);
      }
      const sf = soundfontNotice(result.soundfonts);
      if (sf) notify(sf.level, sf.text);
    })
    .catch((err: unknown) => {
      const message = `Chargement des samples impossible : ${(err as Error).message}`;
      samplesStatus.set('error');
      samplesError.set(message);
      notify('error', message);
      loadPromise = null;
    });
  return loadPromise;
}

